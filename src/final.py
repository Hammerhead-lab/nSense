"""Stage 5: final test evaluation. The only stage that reads the test set.

Each model is fit once on all dev rows at its chosen (train_report.json, baselines_report.json) or
fixed configuration, then predicts the test set once. AUC is reported only; nothing is selected here.

Writes results/test_report.json, results/test_comparison.csv and results/summary.md.
"""
import json
import os

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.neighbors import KNeighborsClassifier
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.tree import DecisionTreeClassifier
from wordfreq import zipf_frequency

from utils import (BINARY, CLASSES, binary_metrics, dev_test_split, direction_feature,
                   fold_metrics, forest, load_config, one_hot, path, pos_tags, set_seed,
                   to_binary, write_json)

THIN = 20  # class x axis cells in the test set below this are not reported per axis


def proba_in(clf, F, classes):
    """predict_proba with its columns checked against clf.classes_ and put in `classes` order."""
    order = list(clf.classes_)
    assert sorted(order) == sorted(classes), f"predict_proba columns {order} vs {classes}"
    return clf.predict_proba(F)[:, [order.index(c) for c in classes]]


def three_class(clf, F, y, dev, test):
    """Fit on dev rows, predict test rows once: three-class and collapsed metrics, and AUC."""
    clf.fit(F[dev], y[dev])
    p = clf.predict(F[test])
    m = fold_metrics(y[dev], clf.predict(F[dev]), y[test], p)
    m["bias_vs_neutral"] = binary_metrics(y[test], to_binary(p))
    # roc_auc_score needs sorted labels; the macro average does not depend on class order.
    labels = sorted(CLASSES)
    m["auc_ovr_macro"] = roc_auc_score(y[test], proba_in(clf, F[test], labels),
                                       multi_class="ovr", average="macro", labels=labels)
    return m


def binary(clf, F, y, dev, test):
    """Fit on to_binary(dev labels), predict test rows once: bias-vs-neutral metrics and AUC."""
    yb = to_binary(y)
    clf.fit(F[dev], yb[dev])
    m = binary_metrics(y[test], clf.predict(F[test]))
    m["train_macro_f1"] = binary_metrics(y[dev], clf.predict(F[dev]))["macro_f1"]
    m["auc"] = roc_auc_score(yb[test] == "bias", proba_in(clf, F[test], BINARY)[:, 0])
    return m


def md_table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def f3(v):
    return "" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.3f}"


def config_label(p):
    return f"d{'∞' if p['max_depth'] is None else p['max_depth']}·{p['n_estimators']}"


def pm(mean, std):
    return f"{mean:.3f} ± {std:.3f}"


def confusion_table(cm, labels):
    return md_table(["true \\ pred"] + labels, [[c] + list(r) for c, r in zip(labels, cm)])


def summary(cfg, out, split, sweep, train_report, comparison, test, test_table, meta):
    best3 = train_report["best_params"]["three_class"]
    best2 = train_report["best_params"]["binary"]
    rf, rfb = test["models"]["random_forest"], test["models"]["random_forest_binary"]
    s = []

    s.append("# Results summary\n")
    s.append("Generated by `src/final.py`. Dev CV numbers come from `train.py` and `baselines.py`; "
             "test numbers from the single test-set evaluation in `final.py`.\n")

    s.append("## 1. How to reproduce\n")
    s.append("```sh\ndocker compose up --build\n```\n")
    s.append(f"- Seed: {cfg['seed']}")
    s.append(f"- Model: `{cfg['model_name']}` at revision `{cfg['model_revision']}`")
    s.append(f"- Dataset: `{cfg['dataset_name']}` ({cfg['dataset_config']}, "
             f"{cfg['dataset_split']}) at revision `{cfg['dataset_revision']}`\n")

    s.append("## 2. Split\n")
    s.append(f"Test set: candidate fold {split['chosen_test_fold']} of "
             f"{cfg['test_n_splits']} (the most class-balanced; DECISIONS 35). "
             f"Actual test share: {100 * split['test_share']:.1f}%.\n")
    sp = split["splits"]
    s.append(md_table(["split", "rows", "groups"] + CLASSES,
                      [[n, sp[n]["rows"], sp[n]["groups"]]
                       + [f"{sp[n]['class_counts'][c]} ({sp[n]['class_pct'][c]:.1f}%)"
                          for c in CLASSES] for n in ("dev", "test")]) + "\n")
    axes = sorted({a for n in sp for c in CLASSES for a in sp[n]["class_by_axis"][c]})
    thin = []
    cells = []
    for c in CLASSES:
        row = [c]
        for a in axes:
            dev_n = sp["dev"]["class_by_axis"][c].get(a, 0)
            test_n = sp["test"]["class_by_axis"][c].get(a, 0)
            row.append(f"{dev_n} / {test_n}")
            if test_n < THIN:
                thin.append(f"{c} × {a} ({test_n})")
        cells.append(row)
    s.append("Class × axis, rows (dev / test):\n")
    s.append(md_table(["class"] + axes, cells) + "\n")
    if thin:
        s.append(f"Test cells under {THIN} rows, not reported per axis: {', '.join(thin)}.\n")

    s.append("## 3. RQ1: label granularity (test set)\n")
    s.append("Same vectors, same learner, same rows. The binary RF is trained on "
             "`binary_map(class)`; the 3-class RF's predictions are collapsed with the same map.\n")
    s.append(md_table(
        ["model", "config", "bias-vs-neutral F1", "F1 innate", "F1 derived"],
        [["binary RF", config_label(best2),
          f3(rfb["macro_f1"]), "n/a", "n/a"],
         ["3-class RF, collapsed", config_label(best3),
          f3(rf["bias_vs_neutral"]["macro_f1"]),
          f3(rf["per_class"]["innate"]["f1-score"]), f3(rf["per_class"]["derived"]["f1-score"])]]))
    s.append(f"\nGap (collapsed 3-class − binary): **{test['rq1']['gap']:+.3f}**. "
             "Across all 12 configurations (CV): [label_gap.png](label_gap.png).\n")

    s.append("## 4. RQ2: robustness across random forest configurations (dev CV)\n")
    s.append(md_table(
        ["max_depth", "trees", "3-class val F1", "3-class train F1", "collapsed bvn F1",
         "binary val bvn F1", "binary train bvn F1", "gap"],
        [[r.max_depth, r.n_estimators, pm(r.three_val_macro_f1_mean, r.three_val_macro_f1_std),
          f3(r.three_train_macro_f1_mean),
          pm(r.three_collapsed_bvn_f1_mean, r.three_collapsed_bvn_f1_std),
          pm(r.binary_val_bvn_f1_mean, r.binary_val_bvn_f1_std), f3(r.binary_train_bvn_f1_mean),
          pm(r.gap_mean, r.gap_std)] for r in sweep.itertuples()]))
    s.append("\nbvn = bias vs neutral; mean ± std over 5 folds.\n")
    s.append(f"- Chosen 3-class RF (max mean CV 3-class macro-F1): {best3}")
    s.append(f"- Chosen binary RF (max mean CV bias-vs-neutral macro-F1): {best2}")
    s.append("- Tie-break within 0.001: fewer trees, then shallower.\n")
    s.append("Figures: [rf_sweep.png](rf_sweep.png), [label_gap.png](label_gap.png).\n")

    s.append("## 5. Supporting: all models\n")
    s.append("Dev CV (`comparison.csv`), 3-class macro-F1 mean ± std over folds:\n")
    s.append(md_table(
        ["model", "macro-F1", "F1 innate", "F1 derived", "F1 neutral", "train macro-F1",
         "bias-vs-neutral F1"],
        [[r.model, "" if pd.isna(r.macro_f1_mean) else pm(r.macro_f1_mean, r.macro_f1_std),
          f3(r.f1_innate), f3(r.f1_derived), f3(r.f1_neutral), f3(r.train_macro_f1_mean),
          f3(r.bias_vs_neutral_f1)] for r in comparison.itertuples()]) + "\n")
    s.append("Test set (`test_comparison.csv`):\n")
    s.append(md_table(
        ["model", "labelling", "3-class macro-F1", "bias-vs-neutral F1", "AUC",
         "F1 innate", "F1 derived", "F1 neutral"],
        [[r.model, r.labelling, f3(r.macro_f1_3class), f3(r.bias_vs_neutral_f1), f3(r.auc),
          f3(r.f1_innate), f3(r.f1_derived), f3(r.f1_neutral)]
         for r in test_table.itertuples()]) + "\n")
    s.append("AUC: macro one-vs-rest for 3-class models, `bias` as positive for the binary RF. "
             "Reported only, never used for selection.\n")
    best = test["best_baseline"]
    s.append("Test confusion matrices, 3-class (rows true, columns predicted):\n")
    s.append(f"Random forest {best3}:\n")
    s.append(confusion_table(rf["confusion_matrix"], CLASSES) + "\n")
    s.append(f"Best baseline by dev CV macro-F1, `{best}`:\n")
    s.append(confusion_table(test["models"][best]["confusion_matrix"], CLASSES) + "\n")

    s.append("## 6. Environment\n")
    s.append(f"- Embedding device: {meta['device']} (`embeddings_meta.json`)")
    s.append(f"- CPU threads available (`os.cpu_count()`): {os.cpu_count()}")

    (out / "summary.md").write_text("\n".join(s) + "\n")


def main():
    cfg = load_config()
    seed = cfg["seed"]
    set_seed(seed)
    out = path(cfg, "results")

    rows = pd.read_csv(path(cfg, "rows"), keep_default_na=False)
    X = np.load(path(cfg, "embeddings"))
    C = np.load(path(cfg, "context_embeddings"))
    assert len(X) == len(C) == len(rows), "embeddings do not match rows.csv; rerun embed.py"
    y = rows["class"].to_numpy()
    axis = rows["axis"].to_numpy()
    dev, test = dev_test_split(rows, cfg)
    split = json.load(open(out / "split_report.json"))
    assert split["splits"]["test"]["rows"] == len(test), "split_report.json is stale; rerun train.py"
    train_report = json.load(open(out / "train_report.json"))
    base = json.load(open(out / "baselines_report.json"))
    best3 = train_report["best_params"]["three_class"]
    best2 = train_report["best_params"]["binary"]
    print(f"Test set: {len(test)} rows, read once here. Dev: {len(dev)} rows.")

    # Features for supporting models, fit on dev rows only.
    direction = direction_feature(X, y, axis, dev, np.concatenate([dev, test]))
    tags_dev, tags_test = pos_tags(rows.iloc[dev]), pos_tags(rows.iloc[test])
    vocab = sorted(set(tags_dev))
    pos = np.zeros((len(rows), len(vocab)), dtype=np.float32)
    pos[dev], pos[test] = one_hot(tags_dev, vocab), one_hot(tags_test, vocab)
    freq = np.zeros((len(rows), 1))
    for idx in (dev, test):
        freq[idx, 0] = [zipf_frequency(w, "en") for w in rows["word"].iloc[idx]]

    lr_C = base["logistic_regression"]["params"]["C"]
    k = base["knn"]["params"]["n_neighbors"]
    models = {
        "random_forest": (forest(seed, **best3), X),
        "logistic_regression": (make_pipeline(StandardScaler(), LogisticRegression(
            C=lr_C, max_iter=5000, random_state=seed)), X),
        "knn": (make_pipeline(StandardScaler(), KNeighborsClassifier(n_neighbors=k)), X),
        "single_direction": (DecisionTreeClassifier(max_depth=2, random_state=seed), direction),
        "part_of_speech": (DecisionTreeClassifier(random_state=seed), pos),
        "frequency": (DecisionTreeClassifier(max_depth=2, random_state=seed), freq),
        "context_only": (forest(seed, **best3), C),
    }
    results = {}
    for name, (clf, F) in models.items():
        results[name] = three_class(clf, F, y, dev, test)
        print(f"  {name} done")
    results["random_forest_binary"] = binary(forest(seed, **best2), X, y, dev, test)
    print("  random_forest_binary done")

    rf, rfb = results["random_forest"], results["random_forest_binary"]
    comparison = pd.read_csv(out / "comparison.csv")
    baselines = comparison[~comparison["model"].str.startswith("random_forest")]
    best_baseline = baselines.loc[baselines["macro_f1_mean"].idxmax(), "model"]
    report = {
        "n_dev": len(dev), "n_test": len(test),
        "params": {"random_forest": best3, "random_forest_binary": best2,
                   "logistic_regression": {"C": lr_C}, "knn": {"n_neighbors": k},
                   "context_only": best3},
        "rq1": {"binary_bias_vs_neutral_f1": rfb["macro_f1"],
                "collapsed_bias_vs_neutral_f1": rf["bias_vs_neutral"]["macro_f1"],
                "gap": rf["bias_vs_neutral"]["macro_f1"] - rfb["macro_f1"],
                "three_class_f1_innate": rf["per_class"]["innate"]["f1-score"],
                "three_class_f1_derived": rf["per_class"]["derived"]["f1-score"]},
        "best_baseline": best_baseline,
        "models": results,
    }
    write_json(report, out / "test_report.json")

    table = []
    for name, m in results.items():
        if name == "random_forest_binary":
            table.append({"model": name, "labelling": "binary", "bias_vs_neutral_f1": m["macro_f1"],
                          "auc": m["auc"],
                          **{f"f1_{c}_bvn": m["per_class"][c]["f1-score"] for c in BINARY}})
            continue
        table.append({"model": name, "labelling": "3-class", "macro_f1_3class": m["test_macro_f1"],
                      "bias_vs_neutral_f1": m["bias_vs_neutral"]["macro_f1"],
                      "auc": m["auc_ovr_macro"],
                      **{f"f1_{c}": m["per_class"][c]["f1-score"] for c in CLASSES},
                      **{f"f1_{c}_bvn": m["bias_vs_neutral"]["per_class"][c]["f1-score"]
                         for c in BINARY}})
    table = pd.DataFrame(table, columns=["model", "labelling", "macro_f1_3class",
                                         "bias_vs_neutral_f1", "auc", "f1_innate", "f1_derived",
                                         "f1_neutral", "f1_bias_bvn", "f1_neutral_bvn"])
    table.to_csv(out / "test_comparison.csv", index=False)

    summary(cfg, out, split, pd.read_csv(out / "rf_sweep.csv", keep_default_na=False),
            train_report, comparison, report, table,
            json.load(open(path(cfg, "embeddings_meta"))))

    with pd.option_context("display.float_format", "{:.3f}".format, "display.width", 160):
        print("\n", table.to_string(index=False), sep="")
    q = report["rq1"]
    print(f"\nRQ1 (test): binary RF {q['binary_bias_vs_neutral_f1']:.3f}, collapsed 3-class RF "
          f"{q['collapsed_bias_vs_neutral_f1']:.3f}, gap {q['gap']:+.3f}; 3-class F1 innate "
          f"{q['three_class_f1_innate']:.3f}, derived {q['three_class_f1_derived']:.3f}")
    print(f"\nWrote {out}/test_report.json, test_comparison.csv, summary.md")


if __name__ == "__main__":
    main()
